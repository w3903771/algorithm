"""BISHI11 变幻莫测 —— 交换 (X,Y)->(Y,X) 与变换 (X,Y)->(X+Y,X-Y)，最少几步使 X=Y。

考点：把操作看成矩阵，发现群是有限的，于是答案只有 0/1/2/3/-1 五种，O(1)。

推导：记 S=[[0,1],[1,0]]，T=[[1,1],[1,-1]]。关键性质 T^2 = 2I，S^2 = I，
      所以任何操作序列化简后都是 S、T 交替的「约化词」，再乘一个正/负常数
      （(ST)^4 = -4I）。而 X=Y 这个条件对整体缩放（含取负）不敏感，
      于是只需枚举交替词，看它给出的判定条件：

        长度 0  I           -> X = Y
        长度 1  T           -> Y = 0
        长度 2  T·S         -> X = 0
        长度 3  T·S·T       -> X + Y = 0
        长度 4 以后条件开始重复（TSTS 又回到 X=Y，STST 回到 X+Y=0）

      所以判定条件一共就 4 个，按步数从小到大判断即可，都不满足就是 -1。

坑：
  1. 必须按 0→1→2→3 的顺序判断，否则 (0,0)、(5,0) 这类会给出偏大的答案。
  2. 连续两次变换等于同时乘 2，不会产生新的可行解，别以为多操作几次就有救。
"""
x, y = map(int, input().split())

if x == y:
    print(0)
elif y == 0:          # 一次变换：(X,Y) -> (X+Y, X-Y)，Y=0 时两边都是 X
    print(1)
elif x == 0:          # 先交换再变换
    print(2)
elif x == -y:         # 变换、交换、变换：最终 (2X, -2Y)
    print(3)
else:
    print(-1)
