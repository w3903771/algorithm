"""BISHI62 斐波那契数列 —— 求 F_k mod (1e9+7)，F_1 = F_2 = 1，k <= 1e6。

这题考什么：
    最基础的线性递推。k <= 1e6，直接 O(k) 递推就够，
    不需要矩阵快速幂 / 快速倍增（那是 k 到 1e18 时才必要的）。

数据规模与复杂度：
    k <= 1e6，单组数据。O(k) 循环 ≈ 1e6 次「加法 + 取模」，Python 约 0.2s。
    注意**不要**算精确大整数 F_k 再取模：F_1e6 有 20 多万位，
    大整数加法本身是 O(位数)，总复杂度会退化成 O(k^2 / 64)，直接 TLE。
    每一步都取模，把数值钉死在 30 位以内。

坑在哪：
  1. 下标从 1 开始，F_1 = F_2 = 1；k = 1 或 2 都输出 1；
  2. 循环里用元组交换 a, b = b, (a+b) % MOD，比手写临时变量快一点；
  3. 取模不能省，理由见上。
"""
import sys

MOD = 1000000007
k = int(sys.stdin.buffer.read().split()[0])
a, b = 0, 1                      # a = F_0, b = F_1
for _ in range(k - 1):
    a, b = b, (a + b) % MOD      # 每步取模，避免大整数退化
sys.stdout.write(str(b % MOD) + "\n")
