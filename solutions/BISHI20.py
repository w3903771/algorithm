"""BISHI20 回文日期 —— 统计 [a,b] 内 YYYYMMDD 形式的回文日期个数。

考点：枚举年份而不是枚举日期。8 位回文数由前 4 位（年份）唯一确定：
      后四位必须是年份的逆序，即 MM = y4y3、DD = y2y1。
      年份只有 1000..9999 共 9000 个，逐个构造再判合法性 + 是否落在区间内，
      复杂度 O(9000)，远优于逐日枚举 9000*365 ≈ 330 万。

坑：
  1. 构造出来的月份可能是 00、20 这类非法值（如 2000 -> 20000002、2002 -> 20022002），
     必须判月份 1..12、日期 1..当月天数。
  2. 闰年 2 月 29 天，且「能被 4 整除但不能被 100 整除，或能被 400 整除」。
  3. 题面说明里写的 "20010002" 是笔误，真正的回文日期是 20011002（2001-10-02）。
"""
import sys

data = sys.stdin.buffer.read().split()
a, b = int(data[0]), int(data[1])

DAYS = [0, 31, 28, 31, 30, 31, 30, 31, 31, 30, 31, 30, 31]

ans = 0
for y in range(1000, 10000):
    s = str(y)
    d = int(s + s[::-1])          # 唯一可能的回文日期
    if d < a or d > b:
        continue
    m, day = d // 100 % 100, d % 100
    if not 1 <= m <= 12:
        continue
    lim = DAYS[m]
    if m == 2 and ((y % 4 == 0 and y % 100 != 0) or y % 400 == 0):
        lim = 29
    if 1 <= day <= lim:
        ans += 1
print(ans)
