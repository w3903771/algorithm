"""BISHI29 小红的排列构造① —— 构造排列 a，使所有 a_i + i 都不是质数。

这题考什么：
    先想「最省事的排列」：恒等排列 a_i = i，此时 a_i + i = 2i。
    2i 是偶数，只要 2i > 2 就一定不是质数；唯一的破绽是 i = 1 时 2i = 2，
    而 2 恰好是质数。所以只需要单独修掉下标 1。

    修法：把位置 1 和位置 3 的值互换，得到 a = [3, 2, 1, 4, 5, ..., n]。
      - i=1: 3+1 = 4 = 2*2，合数；
      - i=2: 2+2 = 4，合数；
      - i=3: 1+3 = 4，合数；
      - i>=4: i+i = 2i >= 8，偶数且大于 2，合数。
    全部满足，且这是一个合法排列。

    n = 1：只有 [1]，1+1 = 2 是质数，无解；
    n = 2：[1,2] -> 2,4，2 是质数；[2,1] -> 3,3，3 是质数；也无解。
    所以 n <= 2 输出 -1，n >= 3 用上面的构造。

数据规模与复杂度：
    n <= 1e5，O(n) 生成 + 一次 " ".join 输出。
    完全不需要筛质数——构造保证了和恒为偶数（>=4），压根不用判素。

坑在哪：
    1. n = 2 也无解，很容易只判 n = 1 就交上去；
    2. 位置 1/3 的交换需要 n >= 3，n = 3 时刚好是 [3,2,1]；
    3. 输出要一行 n 个数，用 " ".join(map(str, ...))，逐个 print 会 TLE；
    4. 答案不唯一（样例给的是另一种排列），本地必须 special judge。
"""
import sys

n = int(sys.stdin.buffer.read().split()[0])
if n <= 2:
    print(-1)
else:
    a = list(range(1, n + 1))
    a[0], a[2] = a[2], a[0]           # 只需把下标 1 的 2 破掉
    sys.stdout.write(" ".join(map(str, a)) + "\n")
