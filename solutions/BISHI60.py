"""BISHI60 大水题 —— 反复数位求和直到只剩一位，输出这一位（数字根）。

这题考什么：
    数字根（digital root）的闭式公式。
    十进制下 10 ≡ 1 (mod 9)，所以「一个数」与「它的数位和」模 9 同余。
    反复求数位和不改变模 9 的值，最终稳定在一个 1..9 的个位数上，于是
        dr(n) = 1 + (n - 1) mod 9      (n >= 1)
    （用 n % 9 会把 9、18、27 算成 0，必须用这个偏移写法。）

数据规模与复杂度：
    n <= 1e9，一组数据，O(1)。
    当然模拟数位求和也就几轮，但公式版更能说明「为什么是 9」。

坑在哪：
  1. n 是 9 的倍数时答案是 9 不是 0；
  2. n = 1 时答案 1，公式给 1 + 0 = 1，正确；
  3. 题目保证 n >= 1，不用管 n = 0（否则数字根是 0）。
"""
import sys

n = int(sys.stdin.buffer.read().split()[0])
sys.stdout.write(str(1 + (n - 1) % 9) + "\n")
