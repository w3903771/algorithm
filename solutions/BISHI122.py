"""BISHI122 区间后缀极大位置计数 —— 每个长度为 k 的窗口内后缀最大值位置的个数。

这题考什么：
    BISHI121 的滑动窗口版。由 BISHI121 的结论：
        「后缀最大值位置的集合」= 单调递减栈（队列）里的元素集合，
    所以本题答案就是**单调递减队列在该窗口下的长度**——
    代码几乎就是滑动窗口最大值模板，只是输出 len(q) 而不是 a[q[0]]。

数据规模与复杂度：
    n <= 1e6，时限「其他语言 2 秒」。O(n)，但常数必须压到极限：
      - 用 `list` + 两个整数指针 h/t 代替 deque，省掉方法调用（快 1.5-2 倍）；
      - 队列长度直接是 t - h + 1，连 len() 调用都省了；
      - 一次性 read / 一次性 join 输出。

坑在哪：
  1. **弹队尾用 `<=`**（相等也弹），因为要求严格大于右边所有元素；
  2. 队首过期判断 `q[h] <= i - k`，写成 `<` 会让窗口变成 k+1 长；
  3. k 可以等于 1，也可以等于 n，两个边界都要能跑；
  4. 输出是 n-k+1 **行**（不是一行空格分隔），和 BISHI114 不同，别抄串了。

Python 现实性：
    n=1e6 + 2 秒限制，读入 0.15s、建表 0.25s、主循环 1.0-1.5s、输出 0.2s，
    非常险。这是「语言差」而不是做法差——能上的优化都上了。
"""
import sys


def main() -> None:
    data = sys.stdin.buffer.read().split()
    n = int(data[0]); k = int(data[1])
    a = list(map(int, data[2:2 + n]))
    q = [0] * n                              # 存下标
    h = 0                                    # 队首（含）
    t = -1                                   # 队尾（含）
    res = []
    push = res.append
    for i in range(n):
        x = a[i]
        while t >= h and a[q[t]] <= x:       # 相等也弹（严格大于）
            t -= 1
        t += 1
        q[t] = i
        if q[h] <= i - k:                    # 队首过期
            h += 1
        if i >= k - 1:
            push(t - h + 1)                  # ★ 答案就是队列长度
    sys.stdout.write("\n".join(map(str, res)) + "\n")


main()
